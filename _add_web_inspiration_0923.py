def main():
    new_cat = {
        "id": "web_inspiration",
        "name": "灵感库精选 | Web Inspiration",
        "subcategories": [{"name": "视频灵感模板 | Video Web Prompts", "templates": templates}],
    }
    for path, tag in ((MAIN, "prompt_templates.json"), (WEB, "templates_data.json")):
        with io.open(path, "r", encoding="utf-8") as f:
            d = json.load(f)
        cats = d["categories"]
        existing = [c for c in cats if c["id"] == "web_inspiration"]
        if existing:
            existing[0]["subcategories"] = new_cat["subcategories"]
            print(tag, "category exists, replaced")
        else:
            cats.append(new_cat)
        # 计数
        n = sum(len(s["templates"]) for c in cats for s in c["subcategories"])
        with io.open(path, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=1)
        print(tag, "updated, total templates:", n)

if __name__ == "__main__":
    main()
